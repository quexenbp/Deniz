"""Generate docs/providers.md from the built-in registry."""

from __future__ import annotations

from pathlib import Path

from deniz.kit.providers.registry import Registry

HEADER = """# Provider catalog

Generated by `scripts/providers_doc.py`; do not edit by hand.

`auth` is what the provider needs, `cost` is the expected quota model. Health
is runtime state and lives in `deniz providers list`. ToS links point at the
source terms; read them before volume use.
"""


def main() -> None:
    registry = Registry(load_plugins=False)
    rows = sorted(registry.infos(), key=lambda i: i.name)
    lines = [HEADER, "| Provider | Capabilities | Auth | Cost | Rate | Response cap | Run budget | Notes | ToS |", "|---|---|---|---|---|---|---|---|---|"]
    for info in rows:
        lines.append(
            f"| `{info.name}` | {', '.join(sorted(info.capabilities))} | {info.auth} | {info.cost} | "
            f"{info.rate:g}/s | {info.max_bytes or '-'} | {info.budget or '-'} | {info.notes} | {info.tos_url or '-'} |"
        )
    Path("docs/providers.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/providers.md ({len(rows)} providers)")


if __name__ == "__main__":
    main()
